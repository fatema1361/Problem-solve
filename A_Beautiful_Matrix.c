#include<stdio.h>
#include<math.h>
int main()
{   
    int arr;
    int r,c;
    for(int i=1;i<=5;i++){
        for(int j=1;j<=5;j++){
            scanf("%d",&arr);
            if(arr==1){
            r=i;
            c=j;
                
            }
        }
    }
    printf("%d\n",abs(r-3)+abs(c-3));


    return 0;
}